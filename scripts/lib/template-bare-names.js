// scripts/lib/template-bare-names.js
// Finds every name our templates use in a way Handlebars resolves as a helper FIRST and as data
// only if no helper of that name exists: `{{name}}`, `{{#name}}…{{/name}}` and `(name)`, each with
// no arguments, one path segment, no `this.`, no `../`, no `@`.
//
// Handlebars helpers are global, shared by every system and module in the world, so each of those
// names is one a module can take over by registering a helper with it. `{{this.name}}` is always a
// data lookup and is never on this list.
//
// A block parameter (`{{#each rows as |row|}}{{row}}{{/each}}`) is skipped, as Handlebars' own
// compiler skips it: inside its block it is always the value, never a helper call.
//
// Used by scripts/gen-template-bare-names.js (writes the list the startup check reads) and by
// tests/templates/foreign-helper-names.test.js (checks that list is current).

import fs from "node:fs";
import path from "node:path";
import Handlebars from "handlebars";

/** Every helper-first name in one template's source, with the line it is on. */
export function bareHelperLookups(source) {
	const found = [];
	const blockParams = [];   // a stack: one entry per enclosing program
	const visitor = new Handlebars.Visitor();

	const head = function (node) {
		const p = node.path;
		if (p.type === "PathExpression" && !p.data && Handlebars.AST.helpers.simpleId(p)
			&& !node.params.length && !node.hash && !blockParams.some(scope => scope.includes(p.parts[0]))) {
			found.push({ name: p.original, line: node.loc.start.line });
		}
		return Handlebars.Visitor.prototype[node.type].call(this, node);
	};
	visitor.MustacheStatement = head;
	visitor.BlockStatement = head;
	visitor.SubExpression = head;
	// A block's `as |a b|` lives on the program it opens, so it is in scope for exactly that body.
	visitor.Program = function (node) {
		blockParams.push(node.blockParams ?? []);
		try { return Handlebars.Visitor.prototype.Program.call(this, node); }
		finally { blockParams.pop(); }
	};

	visitor.accept(Handlebars.parse(source));
	return found;
}

/** Every .hbs under `dir`, recursively, as absolute paths in a stable order. */
export function templateFiles(dir) {
	return fs.readdirSync(dir, { withFileTypes: true })
		.sort((a, b) => a.name.localeCompare(b.name))
		.flatMap(e => e.isDirectory() ? templateFiles(path.join(dir, e.name))
			: e.name.endsWith(".hbs") ? [path.join(dir, e.name)] : []);
}

/** The sorted, de-duplicated helper-first names across every template under `dir`. */
export function templateBareNames(dir) {
	const names = new Set();
	for (const file of templateFiles(dir)) {
		for (const { name } of bareHelperLookups(fs.readFileSync(file, "utf8"))) names.add(name);
	}
	return [...names].sort();
}

/** The text of module/utils/template-bare-names.js for these names. */
export function renderBareNamesModule(names) {
	const rows = [];
	for (let i = 0; i < names.length; i += 8) rows.push(`\t${names.slice(i, i + 8).map(n => JSON.stringify(n)).join(", ")},`);
	return [
		"// GENERATED by scripts/gen-template-bare-names.js. Do not edit: run `npm run gen:template-names`.",
		"// Every name our templates use bare (`{{name}}`, `{{#name}}`, `(name)` with no arguments), which",
		"// Handlebars resolves as a helper before it reads the data. See utils/foreign-helper-check.js.",
		"",
		"export const TEMPLATE_BARE_NAMES = Object.freeze([",
		...rows,
		"]);",
		"",
	].join("\n");
}
